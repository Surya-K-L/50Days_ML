import numpy as np
marks= np.array([45, 78, 92, 56, 88, 72, 95, 61, 83, 77])
print("\nMean: ",np.mean(marks))
print("\nMedian: ",np.median(marks))
print("\nStandard Deviation: ",np.std(marks))
print("\nMinimum Mark: ",np.min(marks))
print("\nMaximum Mark: ",np.max(marks))
print("\nSum of Marks: ",np.sum(marks))
